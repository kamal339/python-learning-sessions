#Operators in Python for example: +, -, *, /, %, **, //, =, ==, !=, >, <, >=, <=, and, or, not

#arthmetic operators
x = 10
y = 5
print("Add ",x + y)  # Output: 15
print("Subtract ",x - y)  # Output: 5
print("Multiply ",x * y)  # Output: 50
print("Divide ",x / y)  # Output: 2.0
print("Modulus ",x % y)  # Output: 0

#comparison operators
print("Equal ",x == y)  # Output: False
print("Greater than ",x > y)  # Output: True
print("Less than ",x < y)  # Output: False
print("Greater than or equal to ",x >= y)  # Output: True
print("Less than or equal to ",x <= y)  # Output: False
print("Not equal ",x != y)  # Output: True


#logical operators , returns 
x= True
y= False
print("And ",x and y)  # Output: False
print("Or ",x or y)  # Output: True
print("Not ",not x)  # Output: False

